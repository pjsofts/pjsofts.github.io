import { defineCollection, z } from 'astro:content';
import { glob } from 'astro/loaders';

const blog = defineCollection({
  loader: glob({ pattern: '**/*.{md,mdx}', base: './src/content/blog' }),
  schema: z.object({
    title: z.string(),
    description: z.string(),
    pubDate: z.coerce.date(),
    updatedDate: z.coerce.date().optional(),
    tags: z.array(z.string()).default([]),
    /** Reading time in minutes, hand-set for accuracy. */
    readingTime: z.number().optional(),
    /** Hero image, root-relative from /public — e.g. "/articles/prompt-caching.png". */
    image: z.string().optional(),
    imageAlt: z.string().optional(),
    featured: z.boolean().default(false),
    draft: z.boolean().default(false),
  }),
});

// Study notes for the Claude Certified Developer – Professional guide.
// Generated by scripts/export_site.py in the certified-architect repo; edit there.
const certification = defineCollection({
  loader: glob({ pattern: '*.md', base: './src/content/certification' }),
  schema: z.object({
    title: z.string(),
    domain: z.number(),
    weight: z.number(),
    description: z.string(),
    lab: z.object({ file: z.string(), url: z.string(), blurb: z.string() }),
  }),
});

export const collections = { blog, certification };
